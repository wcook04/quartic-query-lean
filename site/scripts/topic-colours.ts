#!/usr/bin/env node
// Compute each paper's topic colours once and store them beside its phrases.
//
// Ported from wcook04/lean-exposition site/scripts/topic-colours.ts. For each
// docs/reading_phrases/<paper>.json this writes docs/reading_phrases/colours-<paper>.json: each
// family of topics one hue, each topic one shade of it (src/paper/palette.ts). Papers with the same
// topic list are seriated once on relatedness pooled over all of them. The edition builder
// (tools/reading_phrases.py) reads the stored colours; nothing is computed while a page loads.
//
// Usage: node site/scripts/topic-colours.ts [--check] [--report]
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { palette, relatedness, type FamilyIn, type Palette, type PhraseIn, type TopicIn } from "../src/paper/palette.ts";

export const ROOT = resolve(import.meta.dirname, "../..");
const DIR = resolve(ROOT, "docs/reading_phrases");
const SCHEMA = "topic-colours/1";
const MEANING =
  "Generated by site/scripts/topic-colours.ts from the topics and phrases of this paper and of every paper that shares its topic list; do not edit. Each family has one hue and each topic one shade of it.";

const sectionAt = (text: string) => {
  const heads = [...text.matchAll(/^#{1,6} .*$/gm)].map((m) => [m.index!, m[0]] as const);
  return (offset: number) => {
    let found = "";
    for (const [at, title] of heads) {
      if (at > offset) break;
      found = title;
    }
    return found;
  };
};

export function keyOf(topics: TopicIn[], families?: FamilyIn[]): string {
  const used = new Set(topics.map((t) => t.family).filter(Boolean));
  const canon = JSON.stringify({ topics: topics.map((t) => [t.id, t.family ?? null]), families: (families ?? []).filter((f) => used.has(f.id)).map((f) => [f.id, f.name]) });
  return createHash("sha256").update(canon).digest("hex").slice(0, 16);
}

export interface Computed {
  files: Map<string, string>;
  palettes: { key: string; uses: string[]; topics: number; palette: Palette }[];
}

export function compute(): Computed {
  const lists = new Map<string, { topics: TopicIn[]; families?: FamilyIn[]; related: number[][]; uses: string[] }>();
  const perFile: { path: string; paper: string; key: string }[] = [];
  for (const name of readdirSync(DIR).sort()) {
    if (!/^[a-z0-9-]+\.json$/.test(name) || name.startsWith("colours-")) continue;
    const data = JSON.parse(readFileSync(resolve(DIR, name), "utf8"));
    if (!data.topics || !data.ties) continue;
    const text = existsSync(resolve(ROOT, data.manuscript)) ? readFileSync(resolve(ROOT, data.manuscript), "utf8") : "";
    const section = sectionAt(text);
    const topics: TopicIn[] = data.topics.map((t: TopicIn) => ({ id: t.id, name: t.name, ...(t.family ? { family: t.family } : {}) }));
    const phrases: PhraseIn[] = data.ties.map((row: { topic: string; from: string; after?: string; lean?: { name: string; file?: string }[] }) => {
      const begin = row.after && text.includes(row.after) ? text.indexOf(row.after) + row.after.length : 0;
      const at = text ? text.indexOf(row.from, begin) : -1;
      return { topic: row.topic, section: at >= 0 ? section(at) : "", lean: (row.lean ?? []).map((l) => `${l.file ?? ""}:${l.name}`) };
    });
    const key = keyOf(topics, data.families);
    const rel = relatedness(topics.map((t) => t.id), phrases);
    const colours = resolve(DIR, `colours-${data.paper}.json`);
    const list = lists.get(key);
    if (list) {
      list.related = list.related.map((r, i) => r.map((v, j) => v + rel[i][j]));
      list.uses.push(relative(ROOT, colours));
    } else lists.set(key, { topics, families: data.families, related: rel, uses: [relative(ROOT, colours)] });
    perFile.push({ path: colours, paper: data.paper, key });
  }
  const palettes = new Map([...lists].sort(([a], [b]) => a.localeCompare(b)).map(([key, list]) => [key, palette(list)] as const));
  const files = new Map<string, string>();
  for (const { path, paper, key } of perFile) {
    const p = palettes.get(key)!;
    const body = {
      schema: SCHEMA, paper, meaning: MEANING, key, shared_by: lists.get(key)!.uses.length,
      lightness: p.lightness, chroma: p.chroma, families: p.families,
      topics: Object.fromEntries(p.topics.map((t) => [t.id, { index: t.index, family: t.family, light: t.light, dark: t.dark }])),
    };
    files.set(path, JSON.stringify(body, null, 1) + "\n");
  }
  return { files, palettes: [...lists].map(([key, l]) => ({ key, uses: l.uses, topics: l.topics.length, palette: palettes.get(key)! })) };
}

export function report(c: Computed): string {
  const lines: string[] = [];
  for (const { key, uses, topics, palette: p } of c.palettes) {
    lines.push(`${uses.join(", ")} [${key}] ${topics} topics in ${p.families.length} families ${p.families.map((f) => f.topics.length).join("+")}; L ${p.lightness.light}/${p.lightness.dark}, C ${p.chroma.light}/${p.chroma.dark}`);
    for (const r of p.floors) lines.push(`  ${r.theme.padEnd(5)} ${r.vision.padEnd(12)} families ΔE ≥ ${r.family.toFixed(1).padStart(5)}   shades ΔE ≥ ${Number.isFinite(r.shade) ? r.shade.toFixed(1).padStart(5) : "    —"}   contrast ≥ ${r.contrast.toFixed(2)}`);
  }
  return lines.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes("--check");
  const c = compute();
  let stale = 0;
  for (const [path, content] of c.files) {
    if (existsSync(path) && readFileSync(path, "utf8") === content) continue;
    stale++;
    if (check) console.error(`stale: ${relative(ROOT, path)}`);
    else writeFileSync(path, content);
  }
  if (process.argv.includes("--report")) console.log(report(c));
  if (check && stale) process.exit(1);
  console.log(check ? "topic colours are current" : `topic colours: ${c.files.size} files, ${stale} written`);
}
