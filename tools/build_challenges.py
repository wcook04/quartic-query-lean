#!/usr/bin/env python3
"""Generate Comparator challenges from the statement file and each solution.

A bundle is a folder under lean/QuarticCorpus holding Solution.lean and
comparator.json. The solution marks the part a challenge may see:

    -- CHALLENGE-BEGIN
    open Finset
    theorem name (x : T) : claim := by
      -- proof
      exact implementation x
    -- CHALLENGE-END

Each generated Challenge.lean is the statement vocabulary, copied whole, followed
by that region with every proof replaced by `sorry`. A challenge therefore states
exactly what its solution states, and it imports Mathlib only.
"""

import argparse
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1]
STATEMENT = ROOT / "lean/QuarticQuery/Statement.lean"
CORPUS = ROOT / "lean/QuarticCorpus"
BODY_START = "@[expose] public section"
GENERATED = "-- Generated by tools/build_challenges.py. Edit Solution.lean or Statement.lean."
PROOF_MARK = re.compile(r"^\s*-- proof\s*$")
DECLARATION = re.compile(r"^(/--|theorem\s|lemma\s|-- CHALLENGE-END)")


def statement_body(text):
    """Return the vocabulary with its own header removed."""
    start = text.index(BODY_START)
    return text[start:].rstrip() + "\n"


def challenge_region(solution, name="Solution.lean"):
    """Return the marked region with proof lines replaced by `sorry`."""
    lines = solution.splitlines()
    if lines.count("-- CHALLENGE-BEGIN") != 1 or lines.count("-- CHALLENGE-END") != 1:
        raise ValueError(f"{name}: needs one CHALLENGE-BEGIN and one CHALLENGE-END line")
    begin, end = lines.index("-- CHALLENGE-BEGIN"), lines.index("-- CHALLENGE-END")
    if begin > end:
        raise ValueError(f"{name}: CHALLENGE-END precedes CHALLENGE-BEGIN")
    out, skipping = [], False
    for line in lines[begin + 1:end]:
        if PROOF_MARK.match(line):
            out.append("  sorry")
            skipping = True
            continue
        if skipping and not DECLARATION.match(line):
            continue
        skipping = False
        out.append(line)
    region = "\n".join(out).strip() + "\n"
    if "sorry" not in region:
        raise ValueError(f"{name}: no `-- proof` marker inside the challenge region")
    return region


def namespace_of(solution):
    found = re.findall(r"^namespace (\S+)$", solution, re.M)
    if len(found) != 1:
        raise ValueError("Solution.lean must open exactly one namespace")
    return found[0]


def challenge_text(statement, solution, name="Solution.lean"):
    namespace = namespace_of(solution)
    return (
        "module\n\n"
        f"{GENERATED}\n\n"
        "public import Mathlib\n\n"
        f"{statement_body(statement)}\n"
        f"{BODY_START}\n\n"
        f"namespace {namespace}\n\n"
        f"{challenge_region(solution, name)}\n"
        f"end {namespace}\n"
    )


def theorem_names(solution, name="Solution.lean"):
    namespace = namespace_of(solution)
    region = challenge_region(solution, name)
    return [f"{namespace}.{found}" for found in re.findall(r"^theorem (\S+)", region, re.M)]


def bundles():
    return sorted(path.parent for path in CORPUS.glob("*/Solution.lean"))


def check_config(folder, solution):
    config = json.loads((folder / "comparator.json").read_text(encoding="utf-8"))
    errors = []
    module = f"QuarticCorpus.{folder.name}"
    if config.get("challenge_module") != f"{module}.Challenge":
        errors.append("challenge_module does not match the folder")
    if config.get("solution_module") != f"{module}.Solution":
        errors.append("solution_module does not match the folder")
    if config.get("definition_names") != []:
        errors.append("definition_names must stay empty: definition bodies are compared")
    if sorted(config.get("theorem_names", [])) != sorted(theorem_names(solution)):
        errors.append("theorem_names differ from the theorems in the challenge region")
    if config.get("permitted_axioms") != ["propext", "Quot.sound", "Classical.choice"]:
        errors.append("permitted_axioms must be the three standard axioms")
    return [f"{folder.name}/comparator.json: {error}" for error in errors]


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a challenge is stale")
    args = parser.parse_args()
    statement = STATEMENT.read_text(encoding="utf-8")
    errors = []
    for folder in bundles():
        solution = (folder / "Solution.lean").read_text(encoding="utf-8")
        target = folder / "Challenge.lean"
        wanted = challenge_text(statement, solution, f"{folder.name}/Solution.lean")
        errors += check_config(folder, solution)
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != wanted:
                errors.append(f"{folder.name}/Challenge.lean: stale, run tools/build_challenges.py")
        else:
            target.write_text(wanted, encoding="utf-8")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    print(f"{len(bundles())} challenge bundle(s) {'current' if args.check else 'written'}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
